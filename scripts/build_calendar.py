"""Build the first-visit calendar snapshot from the published JSON backup."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "calendar/data/diary-2026-11-05.json"
data = json.loads(source.read_text())
if data.get("version") != 2 or not isinstance(data.get("entries"), list):
    raise ValueError("Expected a version 2 diary backup")
serialized = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
serialized = serialized.replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
(ROOT / "calendar/published-data.js").write_text(
    "// Generated by scripts/build_calendar.py; edit the JSON backup instead.\n"
    + "window.PUBLISHED_DIARY = " + serialized + ";\n"
)
print(f"Built calendar snapshot: {len(data['entries'])} entries")
