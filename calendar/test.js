const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const assert=require('node:assert/strict');
const {webcrypto,createHash}=require('node:crypto');
const context=vm.createContext({Blob,crypto:webcrypto,atob});
for(const file of ['stickers.js','nutrition.js','photos.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,file),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'app.js'),'utf8').split('const seed =')[0],context);
vm.runInContext('this.N=Nutrition;this.F=FoodStickers;this.P=PhotoStore;this.validate=validateEntries;',context);
const {N,F,P,validate}=context;
const plain=value=>JSON.parse(JSON.stringify(value));
(async()=>{
  for(const [name,kcal] of [['香梨（1个）',42],['两个香梨',84],['半个香梨',21],['1/2个香梨',21],['十二个香梨',504],['香梨150g',63],['半个牛油果',125]])assert.equal(N.calculate(N.makeParts(name)).total,kcal,name);
  assert.equal(N.calculate(N.makeParts('香梨＋玉米汁')).complete,false);
  assert.equal(N.calculate(N.makeParts('1/0个香梨')).complete,false);
  for(const name of ['苹果干','草莓奶茶','牛油果沙拉','香梨汁'])assert.equal(N.match(name),null,name);
  const custom=N.makeParts('吐司')[0];custom.grams=30;custom.customKcal100=250;
  assert.equal(N.calculate([custom]).total,75);
  custom.customKcal100=0;assert.equal(N.calculate([custom]).total,0);
  custom.grams=null;assert.equal(N.calculate([custom]).complete,false);
  assert.equal(F.kind('香梨'),'pear');assert.equal(F.kind('牛乳沙琪玛'),'sweet');
  assert.deepEqual(plain(F.split('猪扒包＋纯玉米汁、菜包')),['猪扒包','纯玉米汁','菜包']);
  const legacy={id:'legacy',date:'2026-10-26',meal:'breakfast',food:'早餐',calories:750,note:'',estimated:true};
  const migrated=validate([legacy])[0];assert.equal(migrated.calories,750);assert.equal(migrated.original.kind,'legacy');
  assert.deepEqual(plain(validate([migrated])[0]),plain(migrated));
  const edited={...migrated,food:'香梨',parts:N.makeParts('香梨')};
  assert.equal(validate([edited])[0].original.text,'早餐');
  assert.throws(()=>validate([{...migrated,date:'2026-02-30'}]));
  assert.throws(()=>validate([{...migrated,parts:[{...migrated.parts[0],grams:-1}]}]));
  assert.throws(()=>validate([{...migrated,parts:[{...migrated.parts[0],customKcal100:NaN}]}]));
  const bytes=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Zct8AAAAASUVORK5CYII=','base64');
  const id=createHash('sha256').update(bytes).digest('hex');
  const ref={id,name:'test.png',type:'image/png',size:bytes.length};
  const raw={id,data:'data:image/png;base64,'+bytes.toString('base64')};
  assert.equal(validate([{...migrated,photos:[ref]}])[0].photos[0].id,id);
  const [decoded]=await P.decodeBackup([raw],[ref]);
  assert.deepEqual(Buffer.from(await decoded.blob.arrayBuffer()),bytes);
  await assert.rejects(P.decodeBackup([],[ref]));
  await assert.rejects(P.decodeBackup([raw,raw],[ref]));
  await assert.rejects(P.decodeBackup([{...raw,data:'data:image/jpeg;base64,'+bytes.toString('base64')}],[ref]));
  await assert.rejects(P.decodeBackup([raw],[{...ref,size:bytes.length+1}]));
  await assert.rejects(P.decodeBackup([{...raw,id:'a'.repeat(64)}],[{...ref,id:'a'.repeat(64)}]));
  console.log('PASS: portion calculations, unknown foods, custom labels, preserved originals, v1/v2 migration, original-byte backup verification and corrupt-backup rejection.');
})().catch(error=>{console.error(error);process.exitCode=1;});
